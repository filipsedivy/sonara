fn main() -> ExitCode {
    if std::env::args().len() > 1 {
        eprintln!("usage: cargo run -p sonara-agent --example gen_agent_docs");
        return ExitCode::from(2);
    }
    match fs::write(output_path(), render()) {
        Ok(()) => {
            println!("wrote {OUTPUT} ({} tools)", TOOLS.len());
            ExitCode::SUCCESS
        }
        Err(err) => {
            eprintln!("gen_agent_docs: cannot write {OUTPUT}: {err}");
            ExitCode::FAILURE
        }
    }
}

/// The path of [`OUTPUT`], from the crate's manifest directory (`crates/sonara-agent`).
fn output_path() -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../..")
        .join(OUTPUT)
}

/// The whole file: the introduction, the index and every tool's section, one per line, with a
/// final newline.
fn render() -> String {
    let mut tools: Vec<&ToolSpec> = TOOLS.iter().collect();
    tools.sort_by_key(|tool| tool.name);
    let index = tools
        .iter()
        .map(|tool| format!("[`{0}`](#{0})", tool.name))
        .collect::<Vec<_>>()
        .join(", ");
    let mut parts = vec![
        intro(),
        format!("{} tools: {index}", tools.len()),
        String::new(),
    ];
    parts.extend(tools.into_iter().map(tool_section));
    let mut text = parts.join("\n");
    text.push('\n');
    text
}

/// [`INTRO`] with the versions, the additions of the API version and the error codes, in the
/// prototype's order.
fn intro() -> String {
    let codes = ErrorCode::ALL
        .iter()
        .map(|code| format!("`{code}`"))
        .collect::<Vec<_>>()
        .join(", ");
    INTRO
        .replace("@API_VERSION@", API_VERSION)
        .replace("@PROTOCOL_VERSION@", &PROTOCOL_VERSION.to_string())
        .replace("@ADDITIONS@", &additions(ADDITIONS))
        .replace("@ERROR_CODES@", &codes)
}

/// What [`API_VERSION`] adds to [`RECORDED_API_VERSION`]: a sentence and one item per addition,
/// or a sentence that it adds nothing.
fn additions(additions: &[Addition]) -> String {
    if additions.is_empty() {
        return format!("{API_VERSION} adds no tool or argument to {RECORDED_API_VERSION}.");
    }
    let mut lines = vec![
        format!("{API_VERSION} adds to {RECORDED_API_VERSION}:"),
        String::new(),
    ];
    lines.extend(
        additions
            .iter()
            .map(|addition| format!("- {}", addition_text(*addition))),
    );
    lines.join("\n")
}

/// One addition as the list of [`additions`] names it, with links to the tools it concerns: a
/// tool, an optional argument of a tool's input, or an optional field of a nested model (such as
/// `NoteInput`) with the tools that take it.
fn addition_text(addition: Addition) -> String {
    let link = |tool: &ToolSpec| format!("[`{0}`](#{0})", tool.name);
    match addition {
        Addition::Tool(name) => format!("the tool [`{name}`](#{name})"),
        Addition::Field { model, field } => {
            let own: Vec<String> = TOOLS
                .iter()
                .filter(|tool| tool.input.name == model)
                .map(link)
                .collect();
            if !own.is_empty() {
                return format!("the optional argument `{field}` of {}", own.join(", "));
            }
            let nested: Vec<String> = TOOLS
                .iter()
                .filter(|tool| {
                    tool.input
                        .input_schema()
                        .pointer(&format!("/$defs/{model}"))
                        .is_some()
                })
                .map(link)
                .collect();
            format!(
                "the optional field `{field}` of `{model}`, in {}",
                nested.join(", ")
            )
        }
    }
}

/// One tool's section: the heading, the title and safety class, the description and, when the
/// tool has parameters, their table. It ends with a newline after the description or the table.
fn tool_section(tool: &ToolSpec) -> String {
    let schema = tool.input.input_schema();
    let no_properties = Map::new();
    let properties = schema
        .get("properties")
        .and_then(Value::as_object)
        .unwrap_or(&no_properties);
    let required: Vec<&str> = schema
        .get("required")
        .and_then(Value::as_array)
        .map(|names| names.iter().filter_map(Value::as_str).collect())
        .unwrap_or_default();
    let mut lines = vec![
        format!("### `{}`", tool.name),
        String::new(),
        format!("*{}* · safety: **{}**", tool.title, tool.safety.as_str()),
        String::new(),
        tool.description(),
        String::new(),
    ];
    if !properties.is_empty() {
        lines.push("| Parameter | Type | Default | Description |".to_owned());
        lines.push("|---|---|---|---|".to_owned());
        for (name, property) in properties {
            let default = if required.contains(&name.as_str()) {
                "required".to_owned()
            } else {
                property.get("default").map(py_json).unwrap_or_default()
            };
            let description = property
                .get("description")
                .and_then(Value::as_str)
                .unwrap_or_default();
            let constraints = constraints(property);
            let description = match (description.is_empty(), constraints.is_empty()) {
                (_, true) => description.to_owned(),
                (true, false) => constraints,
                (false, false) => format!("{description} ({constraints})"),
            };
            lines.push(format!(
                "| `{name}` | {} | {default} | {} |",
                type_name(property).replace('|', "\\|"),
                description.replace('|', "\\|"),
            ));
        }
        lines.push(String::new());
    }
    lines.join("\n")
}

/// The parameter's type as the table shows it (`_type` of the Python generator): a referenced
/// model's name, the members of an `anyOf` or the values of an `enum` joined by `" | "`, a
/// `const` value, `array<item type>`, or the JSON Schema type (`any` without one).
fn type_name(schema: &Value) -> String {
    if let Some(reference) = schema.get("$ref").and_then(Value::as_str) {
        return reference.rsplit('/').next().unwrap_or(reference).to_owned();
    }
    if let Some(members) = schema.get("anyOf").and_then(Value::as_array) {
        return members
            .iter()
            .map(type_name)
            .collect::<Vec<_>>()
            .join(" | ");
    }
    if let Some(values) = schema.get("enum").and_then(Value::as_array) {
        return values.iter().map(py_json).collect::<Vec<_>>().join(" | ");
    }
    if let Some(value) = schema.get("const") {
        return py_json(value);
    }
    match schema.get("type") {
        None => "any".to_owned(),
        Some(Value::String(kind)) if kind == "array" => {
            let any = Value::Object(Map::new());
            format!("array<{}>", type_name(schema.get("items").unwrap_or(&any)))
        }
        Some(Value::String(kind)) => kind.clone(),
        Some(other) => other.to_string(),
    }
}

/// The parameter's constraints in the order of [`CONSTRAINTS`], for example
/// `"min len 1, max len 200"`; empty without any.
fn constraints(schema: &Value) -> String {
    CONSTRAINTS
        .iter()
        .filter_map(|(key, label)| {
            schema
                .get(*key)
                .map(|value| format!("{label} {}", py_str(value)))
        })
        .collect::<Vec<_>>()
        .join(", ")
}

/// Python's `json.dumps(value)` for the scalars that defaults, `enum` and `const` values are
/// (the contract's `Constant`): `null`, `true`, `120.0`, `"auto"`, with ASCII-only strings.
fn py_json(value: &Value) -> String {
    pyjson::dumps(value, 0)
}

/// Python's `str()` of a schema keyword's value: a string as it is, a float as `repr` writes it
/// (`0.25`), any other value as JSON.
fn py_str(value: &Value) -> String {
    match value {
        Value::String(text) => text.clone(),
        Value::Number(number) if number.is_f64() => number
            .as_f64()
            .map_or_else(|| number.to_string(), float_repr),
        other => other.to_string(),
    }
}

#[cfg(test)]
mod tests {
    use std::fs;

    use sonara_agent::contract::versions::Addition;

    use super::{OUTPUT, additions, output_path, render};

    /// The committed file is what the registry renders: CI's freshness check of P2.
    #[test]
    fn the_committed_agent_api_md_is_up_to_date() {
        let committed = fs::read_to_string(output_path()).expect(OUTPUT);
        assert!(
            committed == render(),
            "{OUTPUT} is out of date: run `cargo run -p sonara-agent --example gen_agent_docs`"
        );
    }

    /// The additions are listed with links to the tools they concern.
    #[test]
    fn additions_name_the_tools_they_concern() {
        assert!(additions(&[]).ends_with(" adds no tool or argument to 1.0."));
        let listed = additions(&[
            Addition::Tool("write_controllers"),
            Addition::Field {
                model: "CreateTrack",
                field: "part",
            },
            Addition::Field {
                model: "NoteInput",
                field: "articulation",
            },
        ]);
        let lines: Vec<&str> = listed.lines().collect();
        assert_eq!(
            lines[1..],
            [
                "",
                "- the tool [`write_controllers`](#write_controllers)",
                "- the optional argument `part` of [`create_track`](#create_track)",
                "- the optional field `articulation` of `NoteInput`, in \
                 [`create_midi_clip`](#create_midi_clip), [`add_midi_notes`](#add_midi_notes), \
                 [`edit_midi_notes`](#edit_midi_notes)",
            ]
        );
        assert!(lines[0].ends_with(" adds to 1.0:"));
    }
}
